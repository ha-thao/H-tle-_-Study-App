-- 1. BẢNG NGÀNH HỌC
CREATE TABLE NGANHHOC(
    ID_NGANH VARCHAR(10) PRIMARY KEY NOT NULL,
    TEN_NGANH NVARCHAR(100) NOT NULL,
    GIOI_THIEU NVARCHAR(MAX),
    CHUAN_DAU_RA NVARCHAR(MAX)
);

-- 2. BẢNG SINH VIÊN
CREATE TABLE SINHVIEN(
    MSSV VARCHAR(11) PRIMARY KEY, -- MSSV vẫn là bắt buộc để định danh
    HO_TEN NVARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NULL,      -- Cho phép NULL (Chưa đăng ký)
    MATKHAU VARCHAR(100) NULL,   -- Cho phép NULL (Chưa đăng ký)
    ID_NGANH VARCHAR(10) NOT NULL,
    CONSTRAINT FK_SV_NGANH FOREIGN KEY (ID_NGANH) REFERENCES NGANHHOC(ID_NGANH)
);



-- 3. BẢNG MÔN HỌC

CREATE TABLE MONHOC(
    ID_MON VARCHAR(20) PRIMARY KEY,
    TEN_MON NVARCHAR(100) NOT NULL,
    SO_TIN_CHI INT CONSTRAINT CHK_STC CHECK (SO_TIN_CHI > 0 AND SO_TIN_CHI <= 10)
);

-- 4. BẢNG CHƯƠNG TRÌNH ĐÀO TẠO (Đây là khung cố định để hiện gợi ý trên Python)
CREATE TABLE CHUONGTRINH_DAOTAO( 
    ID_NGANH VARCHAR(10), 
    ID_MON VARCHAR(20), 
    HOC_KY_DU_KIEN INT, 
    LOAI_MON NVARCHAR(50), 
    PRIMARY KEY (ID_NGANH, ID_MON), 
    CONSTRAINT FK_CTDT_NGANH FOREIGN KEY (ID_NGANH) REFERENCES NGANHHOC(ID_NGANH),
    CONSTRAINT FK_CTDT_MON FOREIGN KEY (ID_MON) REFERENCES MONHOC(ID_MON)
); 

-- 5. BẢNG ĐIỂM CHI TIẾT (Đây là nơi Python sẽ INSERT điểm khi SV chọn môn)
CREATE TABLE BANGDIEM(
    ID_DIEM INT PRIMARY KEY IDENTITY(1,1),
    MSSV VARCHAR(11),
    ID_MON VARCHAR(20),
    KY_HOC_THUC_TE INT,      -- Kỳ thực tế SV đăng ký học
    NAM_HOC VARCHAR(20),     -- Ví dụ: 2024-2025
    DIEM_QT DECIMAL(4,2) CONSTRAINT CHK_DIEMQT CHECK (DIEM_QT BETWEEN 0 AND 10.0),
    HESO_QT DECIMAL(2,1) CONSTRAINT CHK_HESOQT CHECK (HESO_QT BETWEEN 0 AND 1.0),
    DIEM_CK DECIMAL(4,2) CONSTRAINT CHK_DIEMCK CHECK (DIEM_CK BETWEEN 0 AND 10.0),
    HESO_CK DECIMAL(2,1) CONSTRAINT CHK_HESOCK CHECK (HESO_CK BETWEEN 0 AND 1.0),
    CONSTRAINT FK_BD_SV FOREIGN KEY (MSSV) REFERENCES SINHVIEN(MSSV),
    CONSTRAINT FK_BD_MON FOREIGN KEY (ID_MON) REFERENCES MONHOC(ID_MON)
);

-- 6. BẢNG TÀI LIỆU FILE
CREATE TABLE TAILIEU(
    ID_FILE INT PRIMARY KEY IDENTITY(1,1),
    MSSV VARCHAR(11) NOT NULL,
    ID_MON VARCHAR(20) NOT NULL,
    TEN_FILE NVARCHAR(200) NOT NULL DEFAULT N'File chưa đặt tên',
    LOAI_FILE VARCHAR(10),
    NGAY_THEM_TL DATETIME DEFAULT GETDATE(),
    CONSTRAINT FK_TL_SV FOREIGN KEY (MSSV) REFERENCES SINHVIEN(MSSV),
    CONSTRAINT FK_TL_MON FOREIGN KEY (ID_MON) REFERENCES MONHOC(ID_MON)
);

-- 7. BẢNG GHI CHÚ
CREATE TABLE GHICHU(
    ID_NOTE INT PRIMARY KEY IDENTITY(1,1),
    MSSV VARCHAR(11) NOT NULL,
    ID_MON VARCHAR(20) NOT NULL,
    TEN_NOTE NVARCHAR(200) NOT NULL,
    NOIDUNG NVARCHAR(MAX),
    NGAY_THEM_NOTE DATETIME DEFAULT GETDATE(),
    CONSTRAINT FK_GC_SV FOREIGN KEY (MSSV) REFERENCES SINHVIEN(MSSV),
    CONSTRAINT FK_GC_MON FOREIGN KEY (ID_MON) REFERENCES MONHOC(ID_MON)
);

-- 8. BẢNG MỤC TIÊU GPA
CREATE TABLE MUCTIEUDIEM(
    ID_TARGET INT PRIMARY KEY IDENTITY(1,1),
    MSSV VARCHAR(11) NOT NULL,
    GPA_TARGET DECIMAL(3,2),
    CONSTRAINT FK_MT_SV FOREIGN KEY (MSSV) REFERENCES SINHVIEN(MSSV)
);

-- 9. BẢNG CHECKLIST
CREATE TABLE CHECKLIST(
    ID_CHECK INT PRIMARY KEY IDENTITY(1,1),
    MSSV VARCHAR(11) NOT NULL,
    DANH_MUC NVARCHAR(50),
    TEN_MUC_TIEU NVARCHAR(255),
    KETQUA NVARCHAR(255),
    CONSTRAINT FK_CL_SV FOREIGN KEY (MSSV) REFERENCES SINHVIEN(MSSV)
);

-- Tạo lại bảng với cột BOOKING_CODE (để lưu mã đẹp olab...)
CREATE TABLE DATPHONGLAB(
    ID_BOOKING INT PRIMARY KEY IDENTITY(1,1),
    MSSV VARCHAR(11),
    NGAY_DAT DATE,
    KHUNG_GIO VARCHAR(50),
    SO_THANH_VIEN INT,
    DS_TV NVARCHAR(MAX),
    TRANGTHAI INT DEFAULT 1 CHECK (TRANGTHAI IN (0,1)),
    BOOKING_CODE NVARCHAR(50) NULL,
    CONSTRAINT FK_LAB_SV FOREIGN KEY (MSSV) REFERENCES SINHVIEN(MSSV)
);

